// Writes src/data/image-sizes.ts: intrinsic width/height of every photo in
// public/images, so next/image can reserve space (no layout shift) and serve
// resized AVIF/WebP. Run after adding photos: `npm run image-sizes`.
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve("public");
const out = path.resolve("src/data/image-sizes.ts");

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((entry) => {
      const full = path.join(dir, entry.name);
      return entry.isDirectory() ? walk(full) : [full];
    }),
  );
  return files.flat();
}

const files = (await walk(path.join(root, "images"))).filter((file) => /\.(jpe?g|png|webp)$/i.test(file));
const sizes = {};
for (const file of files.sort()) {
  const { width, height } = await sharp(file).metadata();
  sizes["/" + path.relative(root, file).split(path.sep).join("/")] = [width, height];
}

const body = Object.entries(sizes)
  .map(([src, [w, h]]) => `  "${src}": [${w}, ${h}],`)
  .join("\n");
await writeFile(
  out,
  `// Generated by scripts/image-sizes.mjs — do not edit by hand.\nexport const imageSizes: Record<string, [number, number]> = {\n${body}\n};\n`,
);
console.log(`${Object.keys(sizes).length} images → ${path.relative(process.cwd(), out)}`);
